"""Static HTML snapshot export, for publishing to GitHub Pages (or anywhere
else static). This is NOT a live view — it's a point-in-time render of the
current DB state, regenerated by re-running `pool export-html` and
committing the output.

Privacy default: individual field-entry names and points are NOT included
in the export (only aggregate counts) unless include_field_names=True is
passed, since the field standings otherwise include ~100+ other people's
names on what would be a public URL.
"""
